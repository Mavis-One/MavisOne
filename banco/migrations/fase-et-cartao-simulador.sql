-- os enums, a tabela de pagamentos à parte (o cartão vive na linha de
-- pagamento do pedido) e as views — o cálculo mora em
-- public/modules/shared/cartao_simulador.js, que a tela e o servidor usam.
--
-- PENDENTE DE CONFIRMAÇÃO (o próprio script pede): o CNPJ da Rede
-- (01.425.787/0001-04) com o contador, antes de emitir.
-- ============================================================================

-- 1. TAXAS DA CREDENCIADORA, versionadas por vigência --------------------------
create table if not exists cartao_taxas (
  id bigserial primary key,
  tabela text not null,
  vigencia date not null,
  credenciadora_cnpj text not null default '',
  canal text not null check (canal in ('maquininha', 'link')),
  bandeira text not null,
  modalidade text not null check (modalidade in ('debito', 'credito', 'pre_pago', 'parcelado_emissor', 'crediario')),
  parcelas smallint not null check (parcelas between 1 and 24),
  taxa numeric(7,4) not null check (taxa >= 0 and taxa < 1),
  prazo_dias smallint,
  prazo_dias_uteis boolean not null default true,
  taxa_por_parcela boolean not null default false,
  atualizado_por text,
  unique (tabela, vigencia, canal, bandeira, modalidade, parcelas)
);
alter table cartao_taxas enable row level security;
create index if not exists idx_cartao_taxas_busca on cartao_taxas (canal, bandeira, modalidade, parcelas, vigencia);

-- 2. FATORES DO SIMULADOR DA LOJA (cliente paga). Não mudam por bandeira. ------
-- empresa_id '' = todas as lojas.
create table if not exists cartao_fatores (
  id bigserial primary key,
  empresa_id text not null default '',
  canal text not null check (canal in ('maquininha', 'link')),
  modalidade text not null check (modalidade in ('debito', 'credito')),
  parcelas smallint not null check (parcelas between 1 and 24),
  fator numeric(10,6) not null check (fator >= 1),
  vigencia date not null,
  atualizado_por text,
  check (modalidade <> 'debito' or parcelas = 1),
  unique (empresa_id, canal, modalidade, parcelas, vigencia)
);
alter table cartao_fatores enable row level security;

-- 3. OS PVs (estabelecimentos na credenciadora) --------------------------------
-- empresa_id fica vazio na carga: as empresas moram no data/db.json, e quem
