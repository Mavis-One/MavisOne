/**
 * O LEIAUTE OFICIAL DA EFD-ICMS/IPI — campo por campo, registro por registro.
 *
 * DE ONDE VEIO, e por que isto é código e não um PDF numa pasta
 * ------------------------------------------------------------
 * Extraído do Guia Prático da EFD-ICMS/IPI versão 3.2.2, atualização de 11 de
 * fevereiro de 2026, publicado pela Receita Federal no portal do SPED
 * (http://sped.rfb.gov.br/item/show/8112). É o Guia em vigor para o leiaute
 * versão 020 — o mesmo COD_VER que aparece no registro 0000 da escrituração
 * de agosto de 2026 desta empresa.
 *
 * O PDF tem 362 páginas e não dá para versionar, revisar em diff nem consultar
 * em tempo de execução. O que o sistema precisa dele é uma coisa só: a ORDEM
 * e a IDENTIDADE dos campos de cada registro. Isso cabe aqui.
 *
 * COMO ISTO FOI CONFERIDO — e é a parte que importa
 * -------------------------------------------------
 * A escrituração de agosto de 2026 foi aceita pela SEFAZ. Ela usa 40
 * registros distintos, e lib/sped-registros.js guarda quantos campos cada um
 * daqueles registros tinha NO ARQUIVO REAL. A contagem daqui bate com a de lá
 * em 40 de 40 — é o que scripts/test-sped-leiaute.js cobra, e é a
 * única prova disponível de que a leitura do PDF não inventou nem perdeu campo.
 *
 * Quatro defeitos de extração foram achados por essa conferência, e nenhum
 * deles era visível de outra forma:
 *
 *   1. O Guia escreve nome de campo COM ACENTO em nove lugares. O registro
 *      E210 tem "VL_RETENÇAO_ST" e "VL_DEDUÇÕES_ST"; o nome de verdade é
 *      ASCII. O extrator não reconhecia a linha, e os oito campos seguintes
 *      caíam com ela — E210 vinha com 7 campos em vez de 15.
 *   2. O campo 10 do E116 e do E250 é escrito "MES_REF*", com o asterisco da
 *      nota de rodapé dentro do nome. Os dois vinham com 9 campos em vez de 10.
 *   3. O campo 02 do G990 tem o tipo colado no traço: "N- -".
 *   4. No PDF, a célula de descrição desce uma linha em relação ao número do
 *      campo: no 0000, o "C 004" do campo 01 (REG) aparece na linha que começa
 *      com "02 COD_VER". Ler o tipo da linha do próprio campo deslocaria TODOS
 *      os tipos em um. Tamanho errado num gerador de SPED dá arquivo rejeitado
 *      ou, pior, aceito com dado truncado.
 *
 * Por causa do (4), tipo/tamanho/decimais NÃO são lidos da linha do campo: são
 * colhidos na ordem do documento e casados com os campos na ordem da coluna
 * Nº, e só quando as duas contagens batem. Quando não batem, o registro fica
 * SEM TIPO em vez de ficar com tipo chutado — ver SEM_TIPO.
 *
 * O QUE ESTE ARQUIVO NÃO TEM
 * --------------------------
 * A COLUNA "OBRIG" (O / OC / N) ficou fora de propósito. Ela sofre do mesmo
 * deslocamento do item (4) e, pior, em dezenas de registros a obrigatoriedade
 * real está na prosa acima da tabela ("obrigatório se o declarante for...").
 * Um campo marcado "obrigatório" por leitura torta de PDF faria o gerador
 * recusar uma escrituração válida. Quem precisar disso lê o Guia.
 *
 * NÃO TEM AS TABELAS EXTERNAS (5.1.1 de ajustes, 5.4 de obrigações, 4.3.2 de
 * CFOP) nem as REGRAS DE VALIDAÇÃO cruzada. Isto é o leiaute, não o validador.
 *
 * E NÃO É UM GERADOR. Ter o leiaute não produz arquivo: dez dos 40 registros
 * usados em agosto não têm origem nenhuma neste sistema (ver `semFonte` em
 * lib/sped-registros.js), e entre eles está o bloco E inteiro — a apuração do
 * imposto. Esta é a peça que faltava, não a última.
 *
 * O FORMATO
 * ---------
 * Um registro por linha, os campos separados por "|", na ordem do leiaute:
 *
 *     NOME:tipo+tamanho[*][.decimais]
 *
 *     REG:C4          texto de 4 posições
 *     COD_VER:N3*     numérico, 3 posições, tamanho variável
 *     VL_DOC:N-.2     numérico sem tamanho fixo, 2 decimais
 *     DT_DOC:N8*      data (o Guia classifica data como N; ver `tipo`)
 *
 * Registro em SEM_TIPO aparece só com os nomes, sem ":".
 *
 * O arquivo da EFD é delimitado por "|", NÃO é de posição fixa — o tamanho é
 * limite de validação, não gabarito de preenchimento com zeros à esquerda.
 */

