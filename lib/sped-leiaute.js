const CAMPO = /^([A-Z0-9_]+)(?::([CND])(-|\d+)(\*?)(?:\.(\d+))?)?$/;

function decodificar(texto) {
  return String(texto).split('|').map((parte, i) => {
    const m = parte.match(CAMPO);
    if (!m) throw new Error('campo mal formado no leiaute: ' + parte);
    return {
      n: i + 1,
      nome: m[1],
      tipo: m[2] || null,
      tam: m[3] === undefined ? null : (m[3] === '-' ? null : Number(m[3])),
      variavel: m[2] ? m[4] === '*' : null,
      dec: m[5] === undefined ? null : Number(m[5])
    };
  });
}

const cache = new Map();

/**
 * Os campos de um registro, na ordem do leiaute. `null` se o registro não
 * existe no Guia — e null é a resposta certa: um registro que o Guia não tem
 * não pode ser escriturado, e devolver lista vazia deixaria isso passar.
 */
function camposDe(reg) {
  const chave = String(reg || '').toUpperCase();
  if (!CRU[chave]) return null;
  if (!cache.has(chave)) cache.set(chave, decodificar(CRU[chave]));
  return cache.get(chave);
}

/** Quantos campos o registro tem, conforme o Guia. `null` se não existe. */
function quantosCampos(reg) {
  const campos = camposDe(reg);
  return campos ? campos.length : null;
}

/** Todos os códigos de registro que o Guia descreve. */
function registros() {
  return Object.keys(CRU);
}

